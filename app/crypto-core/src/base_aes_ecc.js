// ---------------------------------------------------------------------------------------------
// BASE SCHEME  -  faithful re-implementation of the "Hybrid AES-ECC model" of
//   S. Rehman, N. T. Bajwa, M. A. Shah, A. O. Aseeri, A. Anjum,
//   "Hybrid AES-ECC Model for the Security of Data over Cloud Storage",
//   Electronics 10(21):2673, 2021. https://doi.org/10.3390/electronics10212673
//
// The authors' GitHub repository (github.com/sabarehmanciit/Hybrid-AES-ECC-Model) contains only a
// README, so this module follows the algorithm boxes printed in the paper:
//
//   Box 1 (ECC key generation)   : pick private n(a) < n, compute public point  P = n(a) * G
//   Box 2 (AES enc/dec)          : "add the key generated by ECC which is the public key",
//                                  "AES encryption is performed on the input file by using the
//                                   public key which is generated by ECC", and the file is
//                                  "translated by using the public key given by ECC" to decrypt.
//   Figure 3 / Figure 5          : encryption & decryption are performed at the Cloud Service
//                                  Provider after "verification" (server-side encryption).
//
// The paper does not specify the curve, the key-derivation function, the AES mode, IV or padding.
// We choose the most charitable concrete reading:
//   curve  = NIST P-256 (prime256v1)          key = SHA-256(x-coordinate of P) truncated to 128/256 bit
//   mode   = AES-ECB + PKCS#7 (no IV is mentioned anywhere in Box 2)   [variant: CBC with fixed IV]
// Any deterministic function of the PUBLIC key has the same fatal flaw demonstrated in our attack lab.
// ---------------------------------------------------------------------------------------------
import crypto from 'node:crypto';

export const BASE_CURVE = 'prime256v1';

/** Box 1: P = n(a) * G on NIST P-256. Returns raw private scalar and uncompressed public point. */
export function baseKeygen() {
  const ecdh = crypto.createECDH(BASE_CURVE);
  ecdh.generateKeys();
  return { priv: new Uint8Array(ecdh.getPrivateKey()), pub: new Uint8Array(ecdh.getPublicKey(null, 'uncompressed')) };
}

/** Box 2 step II/III: the AES key is "the key generated by ECC which is the public key". */
export function deriveAesKeyFromPublic(pub, bits = 128) {
  const x = pub.subarray(1, 33); // x-coordinate of the public point P
  return new Uint8Array(crypto.createHash('sha256').update(x).digest()).subarray(0, bits / 8);
}

function cipherName(bits, mode) {
  return `aes-${bits}-${mode}`;
}

/**
 * Encrypt a file exactly as Box 2 describes. `mode` is 'ecb' (default, no IV in the paper)
 * or 'cbc' (variant with a fixed all-zero IV, since no IV is stored or transmitted).
 */
export function baseEncrypt(plain, pub, { bits = 128, mode = 'ecb' } = {}) {
  const key = deriveAesKeyFromPublic(pub, bits);
  const iv = mode === 'ecb' ? null : Buffer.alloc(16, 0);
  const c = crypto.createCipheriv(cipherName(bits, mode), key, iv);
  return Buffer.concat([c.update(plain), c.final()]); // Buffer is a Uint8Array subclass (no extra copy)
}

export function baseDecrypt(ct, pub, { bits = 128, mode = 'ecb' } = {}) {
  const key = deriveAesKeyFromPublic(pub, bits);
  const iv = mode === 'ecb' ? null : Buffer.alloc(16, 0);
  const d = crypto.createDecipheriv(cipherName(bits, mode), key, iv);
  return Buffer.concat([d.update(ct), d.final()]);
}

/**
 * ATTACK 1 - "public-key decryption": an outsider who only has (a) the ciphertext from a leaked
 * bucket / malicious insider and (b) the owner's PUBLIC key (published by design) recovers the file.
 * No private key, no brute force: key equivocation H(K | PK) = 0 bits.
 */
export function publicKeyAttack(ct, publicKeyOfOwner, opts) {
  return baseDecrypt(ct, publicKeyOfOwner, opts);
}

// ------------------------------------------------------------------ traced versions (demo UI)
const hex = (b, n = 32) => {
  const h = Buffer.from(b).toString('hex');
  return h.length > n * 2 ? h.slice(0, n * 2) + `… (${b.length} B)` : h;
};

/** Same as baseEncrypt, but returns the list of steps the CSP performs, with real values. */
export function baseEncryptTraced(plain, pub, opts = {}) {
  const { bits = 128, mode = 'ecb' } = opts;
  const steps = [];
  let t0 = performance.now();
  const key = deriveAesKeyFromPublic(pub, bits);
  steps.push({
    actor: 'server',
    title: 'CSP derives the AES key from the owner\'s ECC PUBLIC key (paper, Box 2 step II-III)',
    values: {
      'owner public key P = n(a)·G': hex(pub, 20),
      'x-coordinate of P': hex(pub.subarray(1, 33)),
      [`AES-${bits} key = SHA-256(P.x)[0:${bits / 8}]`]: hex(key),
      'secret input used?': 'NONE - every value above is public',
    },
    ms: +(performance.now() - t0).toFixed(3),
  });
  t0 = performance.now();
  const ct = baseEncrypt(plain, pub, opts);
  const blocks = Math.ceil(ct.length / 16);
  const seen = new Map();
  let dup = 0;
  for (let i = 0; i < ct.length; i += 16) {
    const b = Buffer.from(ct.subarray(i, i + 16)).toString('hex');
    if (seen.has(b)) dup++;
    else seen.set(b, i);
  }
  steps.push({
    actor: 'server',
    title: `CSP encrypts the file with AES-${bits}-${mode.toUpperCase()} (no IV, no MAC, no signature)`,
    values: {
      'plaintext (first bytes)': hex(plain.subarray(0, 24), 24),
      'ciphertext (first bytes)': hex(ct.subarray(0, 24), 24),
      '16-byte blocks': String(blocks),
      'repeated ciphertext blocks': `${dup} (${((100 * dup) / Math.max(1, blocks)).toFixed(1)}%) - identical plaintext blocks give identical ciphertext`,
      'integrity tag stored': 'NONE',
    },
    ms: +(performance.now() - t0).toFixed(3),
  });
  return { ciphertext: ct, steps };
}

export function baseDecryptTraced(ct, pub, opts = {}) {
  const { bits = 128, mode = 'ecb' } = opts;
  const steps = [];
  let t0 = performance.now();
  const key = deriveAesKeyFromPublic(pub, bits);
  steps.push({
    actor: 'server',
    title: 'CSP re-derives the same AES key from the PUBLIC key',
    values: { [`AES-${bits} key`]: hex(key) },
    ms: +(performance.now() - t0).toFixed(3),
  });
  t0 = performance.now();
  let plain;
  try {
    plain = baseDecrypt(ct, pub, opts);
  } catch (e) {
    steps.push({ actor: 'server', title: 'AES decrypt raised a padding error', values: { error: String(e.message) }, ms: +(performance.now() - t0).toFixed(3) });
    return { plain: null, steps, error: 'padding' };
  }
  steps.push({
    actor: 'server',
    title: `AES-${mode.toUpperCase()} decrypt - returns whatever comes out (nothing checks integrity)`,
    values: { 'plaintext (first bytes)': hex(plain.subarray(0, 24), 24), 'integrity verified?': 'NO (scheme has no tag/hash/signature)' },
    ms: +(performance.now() - t0).toFixed(3),
  });
  return { plain, steps };
}
