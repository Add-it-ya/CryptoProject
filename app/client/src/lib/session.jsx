import { createContext, useCallback, useContext, useEffect, useState } from 'react';
import { getJSON, setToken, getToken } from './api.js';
import { useTrace } from './trace.jsx';
import {
  generateUserKeys,
  exportPublicRaw,
  sealPrivateKeys,
  openPrivateKeys,
  deriveAuthToken,
  PBKDF2_ITER,
  hx,
} from '@cryptovault/crypto-core/proposed';
import { toB64, fromB64, fingerprint } from '@cryptovault/crypto-core/encoding';

const Ctx = createContext(null);
const t = () => performance.now();

export function SessionProvider({ children }) {
  const [user, setUser] = useState(null);
  const [keys, setKeys] = useState(null); // { ecdhPriv, ecdsaPriv } - non-extractable, memory only
  const [directory, setDirectory] = useState([]);
  const trace = useTrace();

  const refreshDirectory = useCallback(async () => {
    if (!getToken()) return;
    setDirectory(await getJSON('/users'));
  }, []);

  useEffect(() => {
    if (user) refreshDirectory();
  }, [user, refreshDirectory]);

  const finish = async (res, password) => {
    let t0 = t();
    const opened = await openPrivateKeys(res.user.vault, password);
    trace.push({
      actor: 'browser',
      title: 'Open my key vault locally: PBKDF2(password, salt, 600k) -> AES-GCM decrypt',
      values: {
        salt: res.user.vault.salt,
        iterations: String(res.user.vault.iter),
        'vault ciphertext': res.user.vault.ct.slice(0, 48) + '…',
        result: 'ECDH + ECDSA private keys imported as NON-extractable CryptoKeys (memory only)',
        'my key fingerprint': res.user.fingerprint,
      },
      ms: +(t() - t0).toFixed(1),
    });
    setToken(res.token);
    setKeys(opened);
    setUser(res.user);
  };

  const login = async (username, password) => {
    trace.operation(`LOGIN as ${username}`);
    let t0 = t();
    const authToken = await deriveAuthToken(username, password);
    trace.push({
      actor: 'browser',
      title: 'Derive login token: PBKDF2-SHA256(password, "cryptovault-auth:" + username, 100k)',
      values: { 'authToken (sent instead of password)': authToken.slice(0, 32) + '…', 'password leaves the browser?': 'NO' },
      ms: +(t() - t0).toFixed(1),
    });
    const res = await getJSON('/auth/login', { method: 'POST', body: { username, authToken } });
    trace.push({ actor: 'server', title: 'Server: bcrypt(authToken) matches -> returns JWT + SEALED vault', values: { JWT: res.token.slice(0, 36) + '…' } });
    await finish(res, password);
  };

  const register = async (username, displayName, password) => {
    trace.operation(`REGISTER new user ${username}`);
    let t0 = t();
    const k = await generateUserKeys();
    const ecdhPub = await exportPublicRaw(k.ecdh.publicKey);
    const ecdsaPub = await exportPublicRaw(k.ecdsa.publicKey);
    trace.push({
      actor: 'browser',
      title: 'Generate two NIST P-256 key pairs in the browser (Q = d·G)',
      values: {
        'ECDH public key (for receiving files)': hx(ecdhPub, 24),
        'ECDSA public key (for signing uploads)': hx(ecdsaPub, 24),
        'private keys d': 'random 256-bit scalars - never leave this browser unencrypted',
        fingerprint: await fingerprint(ecdhPub),
      },
      ms: +(t() - t0).toFixed(1),
    });
    t0 = t();
    const vault = await sealPrivateKeys(k, password);
    trace.push({
      actor: 'browser',
      title: `Seal private keys: AES-256-GCM key = PBKDF2(password, random salt, ${PBKDF2_ITER})`,
      values: { salt: vault.salt, 'vault ciphertext': vault.ct.slice(0, 48) + '…' },
      ms: +(t() - t0).toFixed(1),
    });
    const authToken = await deriveAuthToken(username, password);
    const res = await getJSON('/auth/register', {
      method: 'POST',
      body: { username, displayName, authToken, ecdhPub: toB64(ecdhPub), ecdsaPub: toB64(ecdsaPub), vault },
    });
    trace.push({ actor: 'server', title: 'Server stored: public keys, bcrypt(authToken), sealed vault (+ base-scheme ECC pair generated by CSP)' });
    await finish(res, password);
  };

  const logout = () => {
    setToken(null);
    setKeys(null);
    setUser(null);
  };

  const me = user && keys ? { userId: user.id, ecdhPriv: keys.ecdhPriv } : null;
  const userById = (id) => directory.find((u) => u.id === id);
  const pubOf = (id) => {
    const u = userById(id);
    return u ? { ecdhPub: fromB64(u.ecdhPub), ecdsaPub: fromB64(u.ecdsaPub), label: u.username } : null;
  };

  return (
    <Ctx.Provider value={{ user, keys, me, directory, refreshDirectory, login, register, logout, userById, pubOf }}>{children}</Ctx.Provider>
  );
}

export const useSession = () => useContext(Ctx);
