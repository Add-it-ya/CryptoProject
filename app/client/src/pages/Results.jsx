import { useEffect, useState } from 'react';
import { getJSON } from '../lib/api.js';
import { BarChart, Bar, XAxis, YAxis, Tooltip, Legend, ResponsiveContainer, LineChart, Line, CartesianGrid } from 'recharts';

const RED = '#f87171';
const GREEN = '#34d399';
const AX = { stroke: '#94a3b8', fontSize: 12 };

export default function Results() {
  const [r, setR] = useState(null);
  const [err, setErr] = useState('');
  useEffect(() => {
    getJSON('/bench').then(setR).catch((e) => setErr(e.message));
  }, []);
  if (err) return <div className="alert red">{err}</div>;
  if (!r) return <p>loading…</p>;
  const tam = Object.entries(r.e2_tampering).map(([k, v]) => ({
    attack: k.replace(/_/g, ' '),
    base: +((100 * v.base.detected) / v.trials).toFixed(1),
    proposed: +((100 * v.proposed.detected) / v.trials).toFixed(1),
  }));
  const perf = r.e6_performance.map((x) => ({ size: x.size_kib >= 1024 ? `${x.size_kib / 1024} MiB` : `${x.size_kib} KiB`, base: x.base_enc_ms, proposed: x.proposed_enc_ms }));
  const ent = [
    { name: 'original image', v: r.e3_ecb_image.original.entropy_bits_per_byte, rep: r.e3_ecb_image.original.repeated_block_pct },
    { name: 'base (ECB)', v: r.e3_ecb_image.base.entropy_bits_per_byte, rep: r.e3_ecb_image.base.repeated_block_pct },
    { name: 'proposed (GCM)', v: r.e3_ecb_image.proposed.entropy_bits_per_byte, rep: r.e3_ecb_image.proposed.repeated_block_pct },
  ];
  return (
    <div>
      <h2>Experimental results</h2>
      <p className="muted">
        Generated by <code>npm run bench</code> on {r.meta.cpu} ({r.meta.cores} cores), Node {r.meta.node}, OpenSSL {r.meta.openssl}. The same crypto code runs in this app.
      </p>
      <div className="grid2">
        <div className="card">
          <h3>Attack 1: files recovered from public info only</h3>
          <div className="big-vs">
            <div className="red-t">
              <b>{r.e1_public_key_attack.base_recovered}/{r.e1_public_key_attack.files}</b>
              <small>BASE</small>
            </div>
            <div className="green-t">
              <b>{r.e1_public_key_attack.proposed_recovered}/{r.e1_public_key_attack.files}</b>
              <small>PROPOSED</small>
            </div>
          </div>
        </div>
        <div className="card">
          <h3>Same file uploaded twice</h3>
          <div className="big-vs">
            <div className="red-t">
              <b>{r.e4_determinism.base_bit_difference_pct}%</b>
              <small>BASE bits differ (identical, leaks equality)</small>
            </div>
            <div className="green-t">
              <b>{r.e4_determinism.proposed_bit_difference_pct}%</b>
              <small>PROPOSED bits differ (ideal ≈ 50%)</small>
            </div>
          </div>
        </div>
      </div>
      <div className="card">
        <h3>Attack 2: tampering detected (%), {Object.values(r.e2_tampering)[0].trials} trials per attack</h3>
        <ResponsiveContainer width="100%" height={260}>
          <BarChart data={tam}>
            <CartesianGrid stroke="#1e293b" />
            <XAxis dataKey="attack" {...AX} />
            <YAxis domain={[0, 100]} {...AX} />
            <Tooltip contentStyle={{ background: '#0f172a', border: '1px solid #334155' }} />
            <Legend />
            <Bar dataKey="base" name="Base AES-ECC" fill={RED} />
            <Bar dataKey="proposed" name="Proposed" fill={GREEN} />
          </BarChart>
        </ResponsiveContainer>
      </div>
      <div className="grid2">
        <div className="card">
          <h3>Attack 3: ciphertext entropy (bits/byte, max 8)</h3>
          <ResponsiveContainer width="100%" height={230}>
            <BarChart data={ent}>
              <CartesianGrid stroke="#1e293b" />
              <XAxis dataKey="name" {...AX} />
              <YAxis domain={[0, 8]} {...AX} />
              <Tooltip contentStyle={{ background: '#0f172a', border: '1px solid #334155' }} />
              <Bar dataKey="v" name="entropy" fill="#22d3ee" />
            </BarChart>
          </ResponsiveContainer>
          <small className="muted">
            repeated 16-byte blocks: original {ent[0].rep}%, base {ent[1].rep}%, proposed {ent[2].rep}%
          </small>
        </div>
        <div className="card">
          <h3>Encryption time (ms, median)</h3>
          <ResponsiveContainer width="100%" height={230}>
            <LineChart data={perf}>
              <CartesianGrid stroke="#1e293b" />
              <XAxis dataKey="size" {...AX} />
              <YAxis {...AX} />
              <Tooltip contentStyle={{ background: '#0f172a', border: '1px solid #334155' }} />
              <Legend />
              <Line dataKey="base" name="Base (no integrity)" stroke={RED} strokeWidth={2} />
              <Line dataKey="proposed" name="Proposed (+GCM tag, ECDH, signature)" stroke={GREEN} strokeWidth={2} />
            </LineChart>
          </ResponsiveContainer>
        </div>
      </div>
      <div className="card">
        <h3>Avalanche (1-bit change)</h3>
        <table className="tbl">
          <tbody>
            <tr>
              <td>AES block, 1-bit key change</td>
              <td>{r.e5_avalanche.aes_block_1bit_key_change_pct}%</td>
              <td rowSpan={2} className="muted">
                Ideal is 50%. The paper reports 61-64% as "better", but any deviation from 50% means bias, not extra security.
              </td>
            </tr>
            <tr>
              <td>AES block, 1-bit plaintext change</td>
              <td>{r.e5_avalanche.aes_block_1bit_plaintext_change_pct}%</td>
            </tr>
            <tr>
              <td>Whole 4 KiB file, 1-bit plaintext change: BASE</td>
              <td className="red-t">{r.e5_avalanche.whole_file_4KiB_base_pct}%</td>
              <td className="muted">ECB changes only one block, so the rest of the file stays identical.</td>
            </tr>
            <tr>
              <td>Whole 4 KiB file, 1-bit plaintext change: PROPOSED</td>
              <td className="green-t">{r.e5_avalanche.whole_file_4KiB_proposed_pct}%</td>
              <td className="muted">A fresh random key and nonce every time gives a completely new ciphertext.</td>
            </tr>
          </tbody>
        </table>
      </div>
    </div>
  );
}
